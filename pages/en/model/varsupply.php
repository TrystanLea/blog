function model_init()
{
    gen_type = 0
    gen_capacity = 1.0
}

function model_run()
{
    gen_capacity = 1.0
    total_supply = 0

    data = {};
    data['varsupply'] = [];

    for (var hour = 0; hour < hours-1; hour++) {
        var capacityfactors = tenyearsdatalines[hour].split(",");
           
        supply = parseFloat(capacityfactors[gen_type]) * gen_capacity
        total_supply += supply
        
        var time = data_start_time + (hour * 3600);
        data['varsupply'].push(supply);
    }

    gen_capacity_factor = total_supply / (gen_capacity*hours) * 100

    var out = "";
    out += "Generator capacity: "+gen_capacity.toFixed(3)+"kW\n"
    out += "Capacity factor: "+gen_capacity_factor.toFixed(1)+"%\n"
    out += "Total supply: " + (total_supply/10).toFixed(1) + "kWh/y\n"
    $("#out").html(out);
}
// ---------------------------------------------------------------------------    
	
function model_view()
{
    var options = {
        xaxis:{mode:"time", min:view.start*1000, max:view.end*1000, minTickSize: [1, "hour"]},
        yaxes: [],
        grid: {hoverable: true, clickable: true},
        selection: { mode: "x" },
        legend: {show:false, position: "nw"}
    };
    
    var series = [];
    
    series.push({
        label: "Renewable Supply", 
        data:timeseries(data['varsupply']), 
        yaxis:1, 
        color:"#000000", 
        lines: {
            lineWidth:1, 
            fill: false 
        }
    });

    $.plot("#placeholder",series , options);
}

$("body").on("change","#varsupply_gen_type",function(){
    gen_type = parseInt($(this).val());
    model_run();
    model_view();
});


<p>This first example model's the hourly output of a given installed capacity of wind, wave, tidal or solar. The model is not really doing much, it is just loading the capacity factors for every hour from the 10 year dataset and multiplying by the installed capacity. The total electricity generated is calculated as the sum of the electricity generation in each hour and printed along with the average capacity factor at the end.</p>

<p>The units here are not important. The example could just as well be in MW's or GW's. kW's where chosen as the model examples are focused around building a hourly model that's relatable to an average households energy demand. The kW's of installed capacity could just relate to a small share of a much larger wind turbine, solar farm, wave or tidal power installation.</p>

